const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  getProjects: invoke('projects:get'),
  saveProject: invoke('projects:save'),
  deleteProject: invoke('projects:delete'),
  getStatus: invoke('status:get'),
  getLogs: invoke('logs:get'),
  clearLogs: invoke('logs:clear'),
  startService: invoke('svc:start'),
  stopService: invoke('svc:stop'),
  restartService: invoke('svc:restart'),
  startProject: invoke('project:start'),
  stopProject: invoke('project:stop'),
  restartProject: invoke('project:restart'),
  detectFolder: invoke('detect:folder'),
  pickFolder: invoke('dialog:folder'),
  openPath: invoke('shell:openPath'),
  openUrl: invoke('shell:openUrl'),
  portOwner: invoke('port:owner'),
  freePort: invoke('port:free'),
  openVscode: invoke('shell:vscode'),
  openTerminal: invoke('shell:terminal'),
  makeQr: invoke('qr:make'),
  exportLogs: invoke('logs:export'),
  gitStatus: invoke('git:status'),
  gitPull: invoke('git:pull'),
  setProfile: invoke('profile:set'),
  stopAll: invoke('all:stop'),
  ngrokRequests: invoke('ngrok:requests'),
  ngrokClear: invoke('ngrok:clear'),
  exportConfig: invoke('config:export'),
  importConfig: invoke('config:import'),
  depsStatus: invoke('deps:status'),
  runTask: invoke('svc:task'),
  appInfo: invoke('app:info'),
  checkUpdate: invoke('app:check-update'),
  onLog: (cb) => ipcRenderer.on('log', (_e, d) => cb(d)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, d) => cb(d)),
});
